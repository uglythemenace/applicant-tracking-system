-- Interview times that staff offer for a job and candidates pick from their
-- tracking page. A slot is "free" while application_id is null. Booking is a
-- single guarded UPDATE, so two candidates cannot take the same time.
CREATE TABLE IF NOT EXISTS public.interview_slots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
  starts_at timestamptz NOT NULL,
  timezone text,
  location text,
  application_id bigint REFERENCES public.applications(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS interview_slots_one_per_application
  ON public.interview_slots (application_id) WHERE application_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS interview_slots_job_time ON public.interview_slots (job_id, starts_at);

ALTER TABLE public.interview_slots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.interview_slots FROM anon, authenticated;
GRANT ALL ON public.interview_slots TO service_role;
GRANT USAGE, SELECT ON SEQUENCE interview_slots_id_seq TO service_role;
