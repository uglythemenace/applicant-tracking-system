CREATE TABLE IF NOT EXISTS application_status_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id integer NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  status text NOT NULL,
  changed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS application_status_history_app_idx ON application_status_history(application_id, changed_at);
INSERT INTO application_status_history(application_id, status, changed_at)
SELECT id, status, created_at FROM applications a
WHERE NOT EXISTS (SELECT 1 FROM application_status_history h WHERE h.application_id = a.id);

CREATE TABLE IF NOT EXISTS application_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id integer NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  actor_email text NOT NULL,
  action text NOT NULL,
  old_status text,
  new_status text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS application_audit_log_app_idx ON application_audit_log(application_id, created_at DESC);

