-- Support staff-initiated applicant erasure without retaining applicant data
-- in identity claims or application history. Storage cleanup is queued because
-- Supabase Storage and Postgres cannot participate in one transaction.
CREATE TABLE IF NOT EXISTS public.application_resume_deletion_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_path text NOT NULL UNIQUE,
  queued_at timestamptz NOT NULL DEFAULT now(),
  attempt_count integer NOT NULL DEFAULT 0,
  last_attempt_at timestamptz
);

ALTER TABLE public.application_resume_deletion_queue ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.application_resume_deletion_queue FROM anon, authenticated;
GRANT ALL ON public.application_resume_deletion_queue TO service_role;
GRANT USAGE, SELECT ON SEQUENCE application_resume_deletion_queue_id_seq TO service_role;

-- This audit contains the staff actor and time only; it intentionally stores
-- no candidate identifier, email, phone, notes, or résumé filename.
CREATE TABLE IF NOT EXISTS public.application_data_deletion_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_email text NOT NULL,
  deleted_at timestamptz NOT NULL DEFAULT now(),
  resume_cleanup_queued boolean NOT NULL DEFAULT false
);

ALTER TABLE public.application_data_deletion_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.application_data_deletion_log FROM anon, authenticated;
GRANT ALL ON public.application_data_deletion_log TO service_role;
GRANT USAGE, SELECT ON SEQUENCE application_data_deletion_log_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.delete_application_for_retention(
  p_application_id integer,
  p_actor_email text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_application public.applications%ROWTYPE;
  v_email text;
  v_phone text;
BEGIN
  SELECT * INTO v_application
  FROM public.applications
  WHERE id = p_application_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  v_email := lower(trim(coalesce(v_application.email, '')));
  v_phone := CASE
    WHEN nullif(trim(coalesce(v_application.phone_number, '')), '') IS NULL THEN NULL
    ELSE '+' || regexp_replace(trim(v_application.phone_number), '[^0-9]', '', 'g')
  END;

  IF nullif(v_application.resume_path, '') IS NOT NULL THEN
    INSERT INTO public.application_resume_deletion_queue(storage_path)
    VALUES (v_application.resume_path)
    ON CONFLICT (storage_path) DO NOTHING;
  END IF;

  DELETE FROM public.applications WHERE id = p_application_id;

  IF v_email <> '' AND NOT EXISTS (
    SELECT 1 FROM public.applications
    WHERE lower(trim(email)) = v_email
  ) THEN
    DELETE FROM public.application_identity_claims
    WHERE claim_type = 'email' AND normalized_value = v_email;
  END IF;

  IF v_phone IS NOT NULL AND v_phone <> '+' AND NOT EXISTS (
    SELECT 1 FROM public.applications
    WHERE ('+' || regexp_replace(trim(coalesce(phone_number, '')), '[^0-9]', '', 'g')) = v_phone
  ) THEN
    DELETE FROM public.application_identity_claims
    WHERE claim_type = 'phone' AND normalized_value = v_phone;
  END IF;

  INSERT INTO public.application_data_deletion_log(actor_email, resume_cleanup_queued)
  VALUES (lower(trim(p_actor_email)), nullif(v_application.resume_path, '') IS NOT NULL);

  RETURN jsonb_build_object(
    'deleted', true,
    'resume_cleanup_queued', nullif(v_application.resume_path, '') IS NOT NULL
  );
END;
$$;

REVOKE ALL ON FUNCTION public.delete_application_for_retention(integer, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.delete_application_for_retention(integer, text) TO service_role;
